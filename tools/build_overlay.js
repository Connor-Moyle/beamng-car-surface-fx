// Builds mod/ui/modModules/csfxRain/csfxRain.js (one file: the game's UI module loader takes one script per module) from the window drop simulation
// (mod/vehicles/common/carSurfaceFx/sim.js) and tools/overlay/overlay.js.
//   node tools/build_overlay.js          writes the file
//   node tools/build_overlay.js --check  exits 1 when the written file is not what the sources give (run by the tests)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const sim = fs.readFileSync(path.join(root, 'mod/vehicles/common/carSurfaceFx/sim.js'), 'utf8').replace(/\r\n/g, '\n').replace('})(this);', '})(window);');
const overlay = fs.readFileSync(path.join(__dirname, 'overlay/overlay.js'), 'utf8').replace(/\r\n/g, '\n');
if (!sim.includes('})(window);')) throw new Error('sim.js ends differently than expected');

// the module name (csfxRain) must be the folder's and the file's name; the sim only publishes CsfxSim on the window
const out = '// GENERATED by tools/build_overlay.js from sim.js and tools/overlay/overlay.js: edit those, not this file.\n(function () {\n\'use strict\';\n' + sim + '\n' + overlay + '\n})();\n';
const target = path.join(root, 'mod/ui/modModules/csfxRain/csfxRain.js');

if (process.argv.includes('--check')) {
  const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== out) { console.error('csfxRain.js is out of date: run node tools/build_overlay.js'); process.exit(1); }
  console.log('csfxRain.js is up to date');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, out);
  console.log('wrote', path.relative(root, target));
}
