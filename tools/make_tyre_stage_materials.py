"""Tyre wear stage materials: python tools/make_tyre_stage_materials.py <path to BeamNG content/vehicles/common.zip>
For the tyre materials in FAMILY it writes two worn variants, csfx_<name>_worn and csfx_<name>_belts (a material file under vehicles/common, which the game loads with the first car like its own tyre materials: a switch
target that is not in the car's spawn set renders flat black) and the list of the original names for the car side (mod/lua/common/csfx_tyrelook_names.lua). A variant is the car's own stage 0 (its textures
are referenced by path, none are copied) with the tread normal faded and the full-atlas detail overlays of make_tyre_stage_textures.py laid over it. worn = the bald look, belts = the cords showing.
"""
import json, sys, uuid, zipfile, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'mod')
ART = '/art/surfacefx/tyres/'
# The tyre materials whose atlas the overlays of make_tyre_stage_textures.py fit (the tread is the central band of the 1024 x 512 map): only these get stage materials. The other tyre materials of the
# game have other atlases (checked by eye on a contact sheet; some are radial) and keep their normal look.
FAMILY = ('tire', 'tire_01a', 'tire_01f')
WEAR, WEAR_R, CORD, CORD_N = ART + 'tyre_wear_c.data.png', ART + 'tyre_wear_r.data.png', ART + 'tyre_cord_c.data.png', ART + 'tyre_cord_n.normal.png'
# state -> (strength of the car's own tread normal, colour detail map, its strength, roughness detail strength, detail normal map, its strength)
# Only two states exist, because the engine accepts a switch target only if it was made part of the car at spawn (carSurfaceFx_tyres.onJbeamLoadingPhase2 puts them in the glowMap: on = worn,
# on_intense = belts). worn: the flattened tread and sheen carry it, the colour only lifts a little; belts: pale weave colour and a strong weave normal.
STAGES = {
    'worn': (0.04, WEAR, 2.0, 0.7, None, 0),
    'belts': (0.05, CORD, 1.0, 0.0, CORD_N, 1.0),
}

z = zipfile.ZipFile(sys.argv[1])
src = {}
for n in z.namelist():
    if n.startswith('vehicles/common/tires') and n.endswith('materials.json'):
        src.update(json.loads(z.read(n)))
out = {}
for name in FAMILY:
    m = src[name]
    st = (m.get('Stages') or [{}])[0]
    for k, (ns, dmap, dstr, rstr, nmap, nstr) in STAGES.items():
        s = dict(st)
        s['normalMapStrength'] = ns
        s['detailMap'] = dmap
        s['detailBaseColorMapStrength'] = dstr
        if rstr:
            s['roughnessDetailMap'] = WEAR_R
            s['detailRoughnessMapStrength'] = rstr
        if nmap:
            s['detailNormalMap'] = nmap
            s['detailNormalMapStrength'] = nstr
        s['detailScale'] = [1, 1]
        v = {kk: vv for kk, vv in m.items() if kk not in ('Stages', 'name', 'mapTo', 'persistentId')}
        vn = 'csfx_%s_%s' % (name, k)
        v.update(name=vn, mapTo=vn, persistentId=str(uuid.uuid5(uuid.NAMESPACE_URL, vn)), Stages=[s, {}, {}, {}])
        out[vn] = v
os.makedirs(os.path.join(OUT, 'vehicles/common/carSurfaceFx'), exist_ok=True)
with open(os.path.join(OUT, 'vehicles/common/carSurfaceFx/stages.materials.json'), 'w') as f:
    json.dump(out, f, indent=1)
names = sorted({k.rsplit('_', 1)[0][5:] for k in out if k.endswith(('_worn', '_belts'))})
with open(os.path.join(OUT, 'lua/common/csfx_tyrelook_names.lua'), 'w') as f:
    f.write('-- generated by tools/make_tyre_stage_materials.py: the game\'s tyre materials that have csfx_<name>_worn and _belts variants\nreturn {\n')
    for n in names:
        f.write(" '%s',\n" % n)
    f.write('}\n')
print(len(names), 'tyre materials,', len(out), 'variants')
